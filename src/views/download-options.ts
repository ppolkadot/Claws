import type { DownloadMode, ProbeResult, SponsorBlockMode, TranscriptFormat } from "../api";
import { fastSaveHint } from "../processing-options";
import { hasExactSizes, qualityChoices } from "../resolution";
import { TRANSCRIPT_FORMATS, captionChoices, subtitleLimitHint } from "../transcript-options";
import { store } from "../store";
import { chipCheck, chipRadio, segmented, toggle } from "../ui/components";
import { append, h } from "../ui/dom";
import { group, row } from "../ui/layout";
import { subtitleChips } from "../ui/subtitle-chips";
import { AUDIO_FORMATS, NO_CAPTIONS, SPONSOR_CATEGORIES, audioHint, captionSelect, offersSponsorBlock, presetRow, qualityChips, type LinkChoices } from "./download-shared";

export interface OptionsDeps {
  spotify: boolean;
  dismissRefreshNotices(): void;
  scheduleEstimate(): void;
  paintActionLabel(): void;
}

export function mountOptions(r: ProbeResult, choice: LinkChoices, deps: OptionsDeps): HTMLElement {
  const playlist = r.kind === "playlist";
  const qualities = qualityChoices(r, playlist);
  const captions = captionChoices(r);

  // The Type control is built once and stays while the rows below it change, so its
  // thumb slides to the new choice (a CSS spring; still with reduced motion) and the
  // keyboard stays on it. Transcripts are made one video at a time.
  const typeHint = h("span");
  const typeSeg = segmented<DownloadMode>(
    "Type",
    [
      { value: "video", label: "Video", icon: "video" },
      { value: "audio", label: "Audio Only", icon: "music" },
      ...(playlist
        ? []
        : [
            {
              value: "transcript" as const,
              label: "Transcript",
              icon: "captions" as const,
              disabled: !captions.available,
              title: captions.available ? "Text from the site's captions" : NO_CAPTIONS,
            },
          ]),
    ],
    choice.mode,
    (next) => {
      choice.mode = next;
      deps.dismissRefreshNotices();
      paint();
    },
  );
  const typeRow = row("Type", typeSeg.el, typeHint);
  typeRow.hidden = deps.spotify;
  const panel = group(typeRow);
  const body = h("div", { class: "options-body" }, panel);

  const paint = () => {
    const rows: (Node | null)[] = [];
    const hint = playlist
      ? "Transcripts are made one video at a time: open a video's own link to save its captions."
      : captions.available
        ? ""
        : `${NO_CAPTIONS}, so there is no transcript to save.`;
    typeHint.textContent = hint;
    typeHint.hidden = !hint;

    if (choice.mode === "transcript") {
      const formatHint = h("span", { text: TRANSCRIPT_FORMATS.find((f) => f.value === choice.transcriptFormat)?.hint ?? "" });
      rows.push(
        row(
          "Captions",
          captionSelect(captions, choice.caption, (key) => {
            choice.caption = key;
            deps.dismissRefreshNotices();
          }),
          "Made from the site's own captions; Claws does not recognise speech. Automatic captions are generated by the site and can contain errors.",
        ),
        row(
          "Save as",
          chipRadio<TranscriptFormat>("Transcript format", TRANSCRIPT_FORMATS, choice.transcriptFormat, (value) => {
            choice.transcriptFormat = value;
            formatHint.textContent = TRANSCRIPT_FORMATS.find((f) => f.value === value)?.hint ?? "";
          }),
          formatHint,
        ),
      );
    } else if (choice.mode === "video") {
      rows.push(
        row(
          "Quality",
          qualityChips(qualities, choice.height, (value) => {
            choice.height = value;
            deps.scheduleEstimate();
          }),
          qualities.length === 0
            ? "Quality options appear once the site reports them."
            : playlist
              ? "Each video is saved at the largest size it has, up to this limit. Nothing is upscaled."
              : hasExactSizes(r)
                ? "The sizes this video is offered in, by the shorter side. Nothing is upscaled."
                : "Saved at the largest size this video has, up to this limit on its shorter side. Nothing is upscaled.",
        ),
        presetRow(choice.videoPreset, (next) => {
          choice.videoPreset = next;
          deps.scheduleEstimate();
        }),
      );
      if (r.subtitles.length > 0) {
        rows.push(row("Subtitles", subtitleChips(r.subtitles, choice.subs, () => {
          deps.dismissRefreshNotices();
          paint();
        }), subtitleLimitHint(choice.subs.size)));
        if (choice.subs.size > 0) {
          rows.push(
            row(
              "Embed in video",
              toggle("Embed subtitles in the video", choice.embedSubs, (v) => {
                choice.embedSubs = v;
                paint();
              }),
              "Off saves them as separate .srt files.",
            ),
          );
        }
      }
    } else {
      rows.push(
        row(
          "Format",
          chipRadio<string>("Audio format", AUDIO_FORMATS, choice.audioFormat, (value) => {
            choice.audioFormat = value;
            deps.scheduleEstimate();
          }),
          deps.spotify ? `${audioHint()} FLAC and WAV conversion cannot improve the YouTube source quality.` : audioHint(),
        ),
      );
    }
    if (choice.mode !== "transcript") {
      if (playlist) rows.push(playlistFolderRow());
      if (offersSponsorBlock(r)) rows.push(...sponsorBlockRows());
      rows.push(fastSaveRow());
    }
    while (typeRow.nextSibling) typeRow.nextSibling.remove();
    append(panel, rows);
    deps.paintActionLabel();
    deps.scheduleEstimate();
  };

  const playlistFolderRow = () =>
    row(
      "Playlist folder",
      toggle("Save into a playlist folder", choice.playlistFolder, (v) => {
        choice.playlistFolder = v;
      }),
      "Saves the videos into a folder named after the playlist, each numbered by its place in it.",
    );

  // SponsorBlock asks a service Claws does not otherwise contact, so the row says so and
  // nothing is asked while it is off. Fast Save skips it (it rewrites the file).
  const sponsorBlockRows = (): Node[] => {
    const about = "Uses the community SponsorBlock database: yt-dlp asks sponsor.ajay.app about this video.";
    if (choice.fastSave) return [row("SponsorBlock", h("span", { class: "row-note", text: "Off while Fast Save is on" }), "Marking or removing segments rewrites the file, which Fast Save skips.")];
    const hints: Record<SponsorBlockMode, string> = {
      off: `${about} Nothing is asked while this is off.`,
      mark: `${about} The chosen segments become chapter markers; nothing is cut.`,
      remove: `${about} The chosen segments are cut out of the file. A cut can leave a brief glitch, and the saved file is smaller than the size shown.`,
    };
    const hint = h("span", { text: hints[choice.sponsorblock] });
    const mode = segmented<SponsorBlockMode>(
      "SponsorBlock",
      [
        { value: "off", label: "Off" },
        { value: "mark", label: "Mark" },
        { value: "remove", label: "Remove" },
      ],
      choice.sponsorblock,
      (next) => {
        choice.sponsorblock = next;
        paint();
      },
    );
    const rows: Node[] = [row("SponsorBlock", mode.el, hint)];
    if (choice.sponsorblock !== "off") {
      const chips = chipCheck("Kinds of segment", SPONSOR_CATEGORIES, choice.sponsorCategories, () => {
        // At least one kind stays chosen: "on, for nothing" is not a choice.
        if (choice.sponsorCategories.size === 0) {
          choice.sponsorCategories.add("sponsor");
          paint();
        } else deps.scheduleEstimate();
      });
      rows.push(row("Segments", chips, "The kinds of segment to mark or remove."));
    }
    return rows;
  };

  // Fast Save names exactly what it changes for these choices (processing-options.ts, the
  // mirror of the Rust ProcessingPolicy); it never changes the video or audio downloaded.
  const fastSaveRow = () => {
    const hint = fastSaveHint({
      mode: choice.mode === "audio" ? "audio" : "video",
      audioFormat: choice.audioFormat,
      metadata: store.settings.embedMetadata,
      embeddedSubs: choice.mode === "video" && choice.subs.size > 0 && choice.embedSubs,
      fastSave: choice.fastSave,
      sponsorBlock: offersSponsorBlock(r) && choice.sponsorblock !== "off",
    });
    return row(
      "Fast Save",
      toggle("Fast Save", choice.fastSave, (v) => {
        choice.fastSave = v;
        paint();
      }),
      hint,
    );
  };
  paint();
  return body;
}
